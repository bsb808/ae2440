%[text] ## Model: Ramberg-Osgood Equation
%[text] One model that we can use to explain the data is the Ramberg-Osgood equation:
%[text] $\\hat{\\epsilon} = \\frac{\\sigma}{E} + \\left(\\frac{\\sigma}{K}\\right)^n$
%[text] The Young's modules for the material is known:
%[text] $E = 210,000 \\:\\: \\text{MPa}$
%[text] but the coefficients $K$and $n$ are unknown.
%[text] Write a local function to implement the Ramberg-Osgood equation with the following signature:
%[text] ```matlabCodeExample
%[text] function strain = ROE(stress, params)
%[text] ```
%[text] where `params` is a two element vector for the parameters $K$and $n$ in that order.
function strain = ROE(stress, params)
    K = params(1);
    n = params(2);
    E = 210000;
    strain = stress./E + (stress./K).^n;
end
%[text] ### Test the model function
%[text] Test your function with nominal values of $K = 1000$ MPA and $n = 7$.  First test for a scalar value of stress, say 500 MPA.
%[text] For the model (the equation above), with the values $K = 1000$ MPA and $n = 7$ and $\\sigma = 500 \\, \\text{MPA$,   the predicted strain is $\\varepsilon = 0.0102 \\, \\text{mm/mm$.  Verify that your `ROE` function gives the same result.
params = [1000, 7];
strain = ROE(500, params)
%[text] Next test your function with the same nominal parameters for K and n, but for all the experimental values of stress.  The function should be able to take the vector `stress_exp` as an argument and return an array of strain values using array (element-wise) arithmetic.
strain = ROE(stress_exp, params);
%[text] Plot the results on the same axis you used for the experimental data.   You should see that the shape generated by the model is similar to the shape of the date, but that it is a very poor fit.
hold on
plot(strain, stress_exp,"DisplayName","Model");
%[text] ### Cost Function
%[text] The Mean-Squared Error (MSE)  cost function is popular for expressing this intent:
%[text] $\\text{MSE} = \\frac{1}{m} \\sum\_{i=1}^m \\left( y\_i - f(x\_i) \\right)^2\n$
%[text] - The total cost, the scalar we want to minimize.
%[text] - $m$ is the number of data points
%[text] - $y\_i$ is the observed value at the i-th data point
%[text] - $f(x\_i)$ is the predicted value from the Ramberg-Osgood model. \
%[text] $\\text{MSE} = \\frac{1}{m} \\sum\_{i=1}^m \\left( \\mathrm{StrainData}\_i - \\mathrm{StrainModel}\_i \\right)^2\n$
%[text] $\\text{MSE} = \\frac{1}{m} \\sum\_{i=1}^m \\left( \\epsilon\_i - \\hat{\\epsilon}\_i \\right)^2\n$
%[text] How are we doing so far?  For our current fit, with $K = 1000$ MPA and $n = 7$, find the MSE. 
MSE = sum((strain_exp - strain).^2)/length(strain)
