%[text] In this exercise we'll use optimzation to discover the "best" fit between a model of the stress strain relationship and experimental data.  You are provided with a dataset from a materials science experiment and find fit the parameters of an empircal model to explain the relationship by finding model parameters to minimize the error between the data and the model.
%[text] ## Experimental Data
%[text] From tensile experiments on carbon steel, we have the following data.
% Strain [mm/mm]
strain_exp = [0, 0.0023809 0.003749347, 0.005234888, ...
    0.007631515, 0.011446096, 0.017384888, ...
    0.026405375, 0.039775799];
% Stress [MPa]
stress_exp = [0, 500, 550, 600, 660, 720, 780, 840, 900];
%[text] Plot the data (strain on the x-axis, stress on the y-axis) to get a sense of the relationship.
